"""Characterization test for VehicleTracker.update: scripted frames, outputs captured from the code before it was split."""
import numpy as np

from backend.vision.vehicle_tracker import VehicleTracker


class _Box:
    def __init__(self, row):
        self.xyxy = [np.array(row[:4], dtype=float)]
        self.conf = [row[4]]
        self.cls = [row[5]]


class _Boxes:
    def __init__(self, raw):
        self._raw = raw

    def cpu(self):
        return self

    def numpy(self):
        return self

    def __len__(self):
        return len(self._raw)

    def __iter__(self):
        return (_Box(r) for r in self._raw)


class _Result:
    def __init__(self, raw):
        self.boxes = _Boxes(raw)


class _FakeByteTrack:
    """Returns the scripted track rows of the current frame."""

    def __init__(self):
        self.rows = np.empty((0, 8))

    def update(self, det, frame):
        return self.rows


def _script():
    """30 frames at 0.5 s: [(tracked rows, extra raw boxes)]. Row: x1,y1,x2,y2,id,conf,cls,idx."""
    frames = []
    for i in range(30):
        rows = []
        # car 1 and car 2 drive across the frame fast
        rows.append((10 + i * 40, 100, 60 + i * 40, 140, 1, 0.9, 2, 0))
        if i >= 5:
            rows.append((10 + (i - 5) * 50, 200, 70 + (i - 5) * 50, 250, 2, 0.8, 5, 1))
        # motorcycle standing still, with a rider person box overlapping it
        rows.append((300, 300, 320, 330, 3, 0.7, 3, 2))
        rows.append((298, 285, 322, 320, 4, 0.6, 0, 3))
        # car 7 drives up to the motorcycle and stops touching it (collision candidate)
        rows.append((325 + max(0, 8 - i) * 40, 300, 375 + max(0, 8 - i) * 40, 340, 7, 0.75, 2, 6))
        # truck that disappears frames 10-14 and returns
        if not 10 <= i < 15:
            rows.append((500, 50, 600, 120, 5, 0.85, 7, 4))
        # lone person on the road for a few frames
        if 20 <= i < 24:
            rows.append((700, 400, 720, 450, 6, 0.5, 0, 5))
        raw = [(r[0], r[1], r[2], r[3], r[5], r[6]) for r in rows]
        # a vehicle the tracker has not locked onto yet, and a raw lone person
        if i % 3 == 0:
            raw.append((900, 500, 960, 540, 0.4, 2))
        if i % 4 == 0:
            raw.append((50, 600, 70, 650, 0.3, 0))
        frames.append((rows, raw))
    return frames


def _frame_time(i):
    # 0.5 s steps, then long jumps so the stopped vehicles pass STOPPED_ALERT
    return i * 0.5 if i < 24 else 11.5 + (i - 23) * 9.0


def _run():
    tr = VehicleTracker()
    tr.tracker = _FakeByteTrack()
    out = []
    for i, (rows, raw) in enumerate(_script()):
        tr.tracker.rows = np.array(rows, dtype=float).reshape(-1, 8)
        dets, stats, new = tr.update(_Result(raw), None, _frame_time(i))
        out.append((dets, stats, new, list(tr.persons), sorted(tr.riders),
                    len(tr._tracks), len(tr._passes), tr.anomaly()))
    return out


